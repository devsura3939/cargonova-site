const dictionaries: Record<Lang, Record<keyof typeof en, string>> = { en, ka };

const LangContext = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: keyof typeof en) => string;
  tPhrase: (phrase: string) => string;
  tLocation: (loc: string) => string;
}>({
  lang: "en",
  setLang: () => {},
  t: (k) => en[k],
  tPhrase: (p) => p,
  tLocation: (l) => l,
});

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    // Read persisted language after mount so the initial SSR render is stable.
    let stored: Lang | null = null;
    try {
      stored = localStorage.getItem("cargonova-lang") as Lang | null;
    } catch {
      /* storage blocked */
    }
    if (stored === "en" || stored === "ka") {
      // eslint-disable-next-line react-hooks/set-state-in-effect
      setLangState(stored);
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  // Persist on explicit user action only — never on mount, so a reload keeps
  // the stored language instead of being overwritten by the initial state.
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("cargonova-lang", l);
    } catch {
      /* private mode */
    }
  };
  const t = (key: keyof typeof en) => dictionaries[lang][key] ?? en[key];

  /** Translate a dynamic English phrase rendered from data (cargo types, labels). */
  const tPhrase = (phrase: string) => (lang === "ka" ? kaPhrases[phrase] ?? phrase : enPhrases[phrase] ?? phrase);

  /** Translate a dynamic checkpoint location (prefixes like "At sea · " + proper nouns). */
  const tLocation = (loc: string) => {
    if (lang !== "ka") return loc;
    const prefixMap: [string, string][] = [
      ["At sea · ", "ზღვაზე · "],
      ["Corridor · ", "დერეფანი · "],
      [" border region", " სასაზღვრო ზონა"],
    ];
    let out = loc;
    for (const [a, b] of prefixMap) out = out.split(a).join(b);
    return tPhrase(out);
  };

  return <LangContext.Provider value={{ lang, setLang, t, tPhrase, tLocation }}>{children}</LangContext.Provider>;
}

export function useLang() {
  return useContext(LangContext);
}

