/** True when the cell at (lat, lon) is water. */
export function isWater(lat: number, lon: number): boolean {
  const latIdx = Math.min(179, Math.max(0, Math.floor((90 - lat) / 1)));
  const lonIdx = (((Math.floor((lon + 180) / 1)) % 360) + 360) % 360;
  const bit = (latIdx * 360 + lonIdx) >> 3;
  const maskBit = 0x80 >> ((latIdx * 360 + lonIdx) & 7);
  const idx = bytes[bit] & maskBit ? 1 : 0;
  if (idx === 0) return true;
  for (const [eLat, eLon] of WATER_EXCEPTIONS) {
    if (eLat === latIdx && eLon === lonIdx) return true;
  }
  return false;
}

export function isLand(lat: number, lon: number): boolean {
  return !isWater(lat, lon);
}

